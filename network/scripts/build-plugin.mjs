#!/usr/bin/env node
// FILE: build-plugin.mjs
// PATH: network/scripts/build-plugin.mjs
//
// Copies the lineup into the plugin as wp-plugin/channel-network/data/channels.json.
// Only categories and channels go in: files inside a plugin folder are publicly downloadable,
// so the excluded list (which names non-news channels Keith watches) and the added/source
// bookkeeping stay in the repo. Run before every deploy:
//   node scripts/build-plugin.mjs

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(join(ROOT, 'private', 'channels.json'), 'utf8'));
const keep = ['name', 'url', 'channelId', 'category', 'network', 'mergedFanChannels'];
// Habit weight goes out as a relative 1-100 score, never the raw watches-per-week figure.
const max = Math.max(...src.channels.map((c) => c.affinity ?? 0)) || 1;
const weight = (c) => Math.max(1, Math.round((100 * (c.affinity ?? max / 2)) / max));
const out = {
  _note: 'Generated by scripts/build-plugin.mjs from the repo channels.json. Do not edit.',
  categories: src.categories,
  channels: src.channels.map((c) => ({
    ...Object.fromEntries(keep.filter((k) => k in c).map((k) => [k, k === 'mergedFanChannels' ? c[k].map((f) => ({ channelId: f.channelId })) : c[k]])),
    weight: weight(c),
  })),
};
const dest = join(ROOT, 'wp-plugin/channel-network/data');
mkdirSync(dest, { recursive: true });
writeFileSync(join(dest, 'channels.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${out.channels.length} channels, ${out.categories.length} categories → wp-plugin/channel-network/data/channels.json`);

// The "Recently watched" list (from `channels.mjs watched`). Only what the page shows goes in.
const watchedSrc = join(ROOT, 'private', 'watched.json');
if (existsSync(watchedSrc)) {
  const w = JSON.parse(readFileSync(watchedSrc, 'utf8'));
  const slim = { updated: w.updated, from: w.from, to: w.to, items: w.items.map(({ id, title, channelId, uploaderId, uploaderName, day }) => ({ id, title, channelId, uploaderId, uploaderName, day })) };
  writeFileSync(join(dest, 'watched.json'), JSON.stringify(slim, null, 2) + '\n');
  console.log(`wrote ${slim.items.length} watched videos (${slim.from} → ${slim.to}) → wp-plugin/channel-network/data/watched.json`);
} else {
  console.log('no watched.json yet (run: node scripts/channels.mjs watched reviews/<date>.json)');
}
