#!/usr/bin/env node
// FILE: build-plugin.mjs
// PATH: network/scripts/build-plugin.mjs
//
// Copies the lineup into the plugin as wp-plugin/channel-network/data/channels.json.
// Only categories and channels go in: files inside a plugin folder are publicly downloadable,
// so the excluded list (which names non-news channels Keith watches) and the added/source
// bookkeeping stay in the repo. Run before every deploy:
//   node scripts/build-plugin.mjs [--history <file>]
//
// Also splits the watch-history archive (private/history.json, from `channels.mjs history`)
// into data/history/: index.json (days, counts, channel table; inlined into the /history
// page by PHP) and one YYYY-MM.json per month that the page fetches as it scrolls.
// --history points at another archive (dev: a synthetic one from dev/make-history.mjs).

import { readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(join(ROOT, 'private', 'channels.json'), 'utf8'));
const keep = ['name', 'url', 'channelId', 'category', 'network', 'mergedFanChannels'];
// Habit weight goes out as a relative 1-100 score, never the raw watches-per-week figure.
const max = Math.max(...src.channels.map((c) => c.affinity ?? 0)) || 1;
const weight = (c) => Math.max(1, Math.round((100 * (c.affinity ?? max / 2)) / max));
const out = {
  _note: 'Generated by scripts/build-plugin.mjs from the repo channels.json. Do not edit.',
  categories: src.categories,
  channels: src.channels.map((c) => ({
    ...Object.fromEntries(keep.filter((k) => k in c).map((k) => [k, k === 'mergedFanChannels' ? c[k].map((f) => ({ channelId: f.channelId })) : c[k]])),
    weight: weight(c),
  })),
};
const dest = join(ROOT, 'wp-plugin/channel-network/data');
mkdirSync(dest, { recursive: true });
writeFileSync(join(dest, 'channels.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${out.channels.length} channels, ${out.categories.length} categories → wp-plugin/channel-network/data/channels.json`);

// The "Recently watched" list (from `channels.mjs watched`). Only what the page shows goes in.
const watchedSrc = join(ROOT, 'private', 'watched.json');
if (existsSync(watchedSrc)) {
  const w = JSON.parse(readFileSync(watchedSrc, 'utf8'));
  const slim = { updated: w.updated, from: w.from, to: w.to, items: w.items.map(({ id, title, channelId, uploaderId, uploaderName, day }) => ({ id, title, channelId, uploaderId, uploaderName, day })) };
  writeFileSync(join(dest, 'watched.json'), JSON.stringify(slim, null, 2) + '\n');
  console.log(`wrote ${slim.items.length} watched videos (${slim.from} → ${slim.to}) → wp-plugin/channel-network/data/watched.json`);
} else {
  console.log('no watched.json yet (run: node scripts/channels.mjs watched reviews/<date>.json)');
}

// ---- Watch history (the /history view) ----
// Compact on purpose: at ~50 videos a day the archive grows by ~18k items a year.
//   index.json  { v, updated, from, to, total,
//                 cats: [category keys],
//                 ch:   [[parentChannelId, catIndex]],
//                 up:   [[uploaderId, uploaderName, chIndex]]   (sorted by id),
//                 days: [[YYYY-MM-DD, total, [count per cat]]]  (newest first),
//                 months: { "YYYY-MM": "<content hash>" } }
//   YYYY-MM.json { m, d: { "YYYY-MM-DD": [[videoId, title, upIndex], …] } }  (history order)
const hi = process.argv.indexOf('--history');
const historySrc = hi > 0 ? process.argv[hi + 1] : join(ROOT, 'private', 'history.json');
const histDest = join(dest, 'history');
rmSync(histDest, { recursive: true, force: true });
if (existsSync(historySrc)) {
  const h = JSON.parse(readFileSync(historySrc, 'utf8'));
  const cats = out.categories.map((c) => c.key);
  const parents = new Map(out.channels.map((c) => [c.channelId, c]));
  const items = h.items.filter((it) => parents.has(it.channelId) && cats.includes(parents.get(it.channelId).category));
  const chIds = [...new Set(items.map((it) => it.channelId))].sort();
  const chIdx = new Map(chIds.map((id, i) => [id, i]));
  const ups = new Map();
  for (const it of items) if (!ups.has(it.uploaderId)) ups.set(it.uploaderId, [it.uploaderId, it.uploaderName, chIdx.get(it.channelId)]);
  const upList = [...ups.values()].sort((a, b) => a[0].localeCompare(b[0]));
  const upIdx = new Map(upList.map((u, i) => [u[0], i]));
  const days = new Map(), months = new Map();
  for (const it of items) {
    const ci = cats.indexOf(parents.get(it.channelId).category);
    if (!days.has(it.day)) days.set(it.day, [it.day, 0, cats.map(() => 0)]);
    const row = days.get(it.day); row[1]++; row[2][ci]++;
    const m = it.day.slice(0, 7);
    if (!months.has(m)) months.set(m, {});
    (months.get(m)[it.day] ||= []).push([it.id, it.title, upIdx.get(it.uploaderId)]);
  }
  mkdirSync(histDest, { recursive: true });
  const hashes = {};
  for (const [m, d] of months) {
    const body = JSON.stringify({ m, d });
    hashes[m] = createHash('sha256').update(body).digest('hex').slice(0, 10);
    writeFileSync(join(histDest, `${m}.json`), body);
  }
  const dayList = [...days.values()].sort((a, b) => b[0].localeCompare(a[0]));
  const index = { v: 1, updated: h.updated, from: dayList.at(-1)?.[0] || null, to: dayList[0]?.[0] || null, total: items.length, cats, ch: chIds.map((id) => [id, chIdx.get(id) !== undefined ? cats.indexOf(parents.get(id).category) : 0]), up: upList, days: dayList, months: hashes };
  writeFileSync(join(histDest, 'index.json'), JSON.stringify(index));
  // Server hints for the month files. LiteSpeed on deprogrammer.org compresses JavaScript but
  // sends .json uncompressed and uncached (checked 2026-11-19), so this folder labels them as
  // JavaScript to get them gzipped (the page only fetch()es them; nothing executes them), and
  // caches them for a year: every URL carries a content hash (?v=), so a change is a new URL.
  // index.json is read by PHP, not by visitors.
  writeFileSync(join(histDest, '.htaccess'), [
    '# Generated by scripts/build-plugin.mjs. Do not edit.',
    '<IfModule mod_mime.c>',
    '  AddType text/javascript .json',
    '</IfModule>',
    '<IfModule mod_headers.c>',
    '  <FilesMatch "^[0-9]{4}-[0-9]{2}\\.json$">',
    '    Header set Cache-Control "public, max-age=31536000, immutable"',
    '    Header set X-Content-Type-Options "nosniff"',
    '  </FilesMatch>',
    '  <Files "index.json">',
    '    Header set Cache-Control "no-cache"',
    '  </Files>',
    '</IfModule>',
    '',
  ].join('\n'));
  const size = (f) => readFileSync(join(histDest, f)).length;
  console.log(`wrote watch history: ${items.length} videos, ${dayList.length} days, ${months.size} month files (${Math.round([...months.keys()].reduce((n, m) => n + size(m + '.json'), 0) / 1024)} KB) + index (${Math.round(size('index.json') / 1024)} KB) → wp-plugin/channel-network/data/history/`);
} else {
  console.log('no history.json yet (run: node scripts/channels.mjs history)');
}
